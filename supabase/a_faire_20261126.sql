-- Espace « À faire » : tâches tirées des notes et des comptes rendus d'appel, ou ajoutées à la main.
create table if not exists public.crm_tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid(),
  prospect_id uuid references public.prospects(id) on delete cascade,
  titre text not null check (length(titre) between 1 and 300),
  echeance date,
  kind text,
  origine text not null default 'manuel',
  extrait text,
  fait_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);
comment on table public.crm_tasks is 'À faire : tâches tirées des notes, des appels, ou ajoutées à la main. Faite = fait_at rempli.';
create index if not exists crm_tasks_open_idx on public.crm_tasks (user_id, echeance) where fait_at is null;
create index if not exists crm_tasks_prospect_idx on public.crm_tasks (prospect_id);

alter table public.crm_tasks enable row level security;
drop policy if exists own_data on public.crm_tasks;
create policy own_data on public.crm_tasks for all
  using (user_id = coalesce((select public.crm_owner_id()), (select auth.uid())))
  with check (user_id = coalesce((select public.crm_owner_id()), (select auth.uid())));

drop trigger if exists crm_set_owner on public.crm_tasks;
create trigger crm_set_owner before insert on public.crm_tasks for each row execute function public.crm_set_owner();
drop trigger if exists crm_log_activity on public.crm_tasks;
create trigger crm_log_activity after insert or update or delete on public.crm_tasks for each row execute function public.crm_log_activity();

-- Un devis créé pour la fiche coche les tâches « devis » encore ouvertes.
create or replace function public.crm_tasks_quote_done()
returns trigger language plpgsql security definer set search_path = pg_catalog, public as $$
begin
  if new.type = 'DEV' and new.prospect_id is not null then
    update public.crm_tasks set fait_at = now()
     where prospect_id = new.prospect_id and kind = 'devis' and fait_at is null and created_at <= now();
  end if;
  return null;
end $$;
drop trigger if exists crm_tasks_quote_done on public.documents;
create trigger crm_tasks_quote_done after insert on public.documents
  for each row execute function public.crm_tasks_quote_done();

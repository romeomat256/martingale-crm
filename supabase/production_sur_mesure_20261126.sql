-- Production : suivi des commandes personnalisées, attribuées à la main à un conteneur.
-- Une ligne « sur-mesure » d'un devis accepté ou facturé crée sa commande à produire.
-- Une fiche du configurateur peut aussi être importée à la main.

alter table public.conteneurs add column if not exists fin_production date;

create table if not exists public.crm_custom_orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid(),
  prospect_id uuid references public.prospects(id) on delete set null,
  quote_num text,
  line_key text,
  client text,
  ref text,
  label text,
  config jsonb,
  img text,
  qty integer not null default 1 check (qty > 0),
  conteneur_id uuid references public.conteneurs(id) on delete set null,
  statut text not null default 'a_produire' check (statut in ('a_produire', 'livree')),
  source text not null default 'devis',
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.crm_custom_orders is 'Production : chaises personnalisées à produire, attribuées à la main à un conteneur.';
create unique index if not exists crm_custom_orders_line_idx on public.crm_custom_orders (user_id, quote_num, line_key) where quote_num is not null;

alter table public.crm_custom_orders enable row level security;
drop policy if exists own_data on public.crm_custom_orders;
create policy own_data on public.crm_custom_orders for all
  using (user_id = coalesce((select public.crm_owner_id()), (select auth.uid())))
  with check (user_id = coalesce((select public.crm_owner_id()), (select auth.uid())));
drop trigger if exists crm_set_owner on public.crm_custom_orders;
create trigger crm_set_owner before insert on public.crm_custom_orders for each row execute function public.crm_set_owner();
drop trigger if exists crm_log_activity on public.crm_custom_orders;
create trigger crm_log_activity after insert or update or delete on public.crm_custom_orders for each row execute function public.crm_log_activity();

-- Lignes sur-mesure d'un devis accepté ou facturé : une commande à produire par ligne.
create or replace function public.crm_custom_orders_from_quote(p_doc public.documents)
returns integer language plpgsql security definer set search_path = pg_catalog, public as $$
declare n integer;
begin
  if p_doc.type <> 'DEV' or coalesce(p_doc.statut, '') not in ('Accepté', 'Facturé') then return 0; end if;
  insert into public.crm_custom_orders (user_id, prospect_id, quote_num, line_key, client, ref, label, config, img, qty, source, created_at)
  select p_doc.user_id, p_doc.prospect_id, p_doc.num, coalesce(nullif(li ->> 'prodId', ''), 'ligne-' || ord),
         coalesce(nullif(p_doc.company, ''), nullif(p_doc.client_name, ''), p_doc.contact),
         nullif(li ->> 'productRef', ''),
         coalesce(nullif(li ->> 'productLabel', ''), nullif(li ->> 'productName', ''), 'Chaise sur-mesure'),
         li -> 'productConfig', nullif(li ->> 'productImg', ''),
         greatest(1, coalesce(nullif(li ->> 'qty', '')::numeric, 1)::int), 'devis', now()
    from jsonb_array_elements(case when jsonb_typeof(p_doc.line_items) = 'array' then p_doc.line_items else '[]'::jsonb end) with ordinality as t(li, ord)
   where li ->> 'productCategory' = 'sur-mesure' or coalesce(li ->> 'prodId', '') ~ '^(cfg-|custom-)'
  on conflict (user_id, quote_num, line_key) where quote_num is not null do nothing;
  get diagnostics n = row_count;
  return n;
end $$;
revoke all on function public.crm_custom_orders_from_quote(public.documents) from public, anon, authenticated;

create or replace function public.crm_custom_orders_trg()
returns trigger language plpgsql security definer set search_path = pg_catalog, public as $$
begin
  if new.type = 'DEV' and new.statut in ('Accepté', 'Facturé')
     and (tg_op = 'INSERT' or old.statut is distinct from new.statut) then
    perform public.crm_custom_orders_from_quote(new);
  end if;
  return null;
end $$;

drop trigger if exists crm_custom_orders_from_quote on public.documents;
create trigger crm_custom_orders_from_quote after insert or update of statut on public.documents
  for each row execute function public.crm_custom_orders_trg();

-- Reprise : devis déjà acceptés ou facturés.
select public.crm_custom_orders_from_quote(d) from public.documents d
 where d.type = 'DEV' and d.statut in ('Accepté', 'Facturé');
